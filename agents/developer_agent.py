"""Developer Agent Implementation

Writes and edits Python code per assigned tasks. Uses local file editing,
git for version control. Reports diffs and changes to memory.

Safe by default: writes only to ./src/ directory, never executes arbitrary
code from external input without manager approval.
"""
from __future__ import annotations
import asyncio
import os
import shutil
import time
from pathlib import Path

from agents.base import BaseAgent, Task, Result

SRC_DIR = Path("/sdcard/omid-ai/src")
PROJECT_DIR = Path("/sdcard/omid-ai")


class DeveloperAgent(BaseAgent):
    name = "Developer"
    display_name = "Developer Agent"

    async def execute(self, task: Task) -> Result:
        start = time.time()
        desc = task.description.strip()

        # Default: write a python module for the core functionality described
        filename = self._derive_filename(desc)
        filepath = SRC_DIR / filename

        # Create project dir if needed
        SRC_DIR.mkdir(parents=True, exist_ok=True)

        # Write initial module
        code = self._generate_code(desc, filename)
        with open(filepath, "w") as f:
            f.write(code)

        # Git init (best effort — doesn't fail the task)
        try:
            if not (PROJECT_DIR / ".git").exists():
                os.system("git init 2>/dev/null && git add . 2>/dev/null && git commit -m 'omid initial' 2>/dev/null")
        except Exception:
            pass

        # Smoke test the generated code
        test_ok = True
        try:
            mod = await asyncio.to_thread(self._run_smoke_test, filepath, desc)
            if not mod:
                test_ok = False
        except Exception as e:
            test_ok = False

        result = Result(
            task_id=task.id,
            success=test_ok,
            output={"file": str(filepath), "smoke_tested": test_ok, "code_preview": code[:200]},
            execution_time_ms=round((time.time() - start) * 1000, 2),
        )
        self.store_result(result)
        return result

    def _derive_filename(self, desc: str) -> str:
        words = desc.strip().split()
        ext = ".py" if "python" in desc.lower() or words[0].lower() == "module" else ".py"
        safe = "".join(c for c in words[0] if c.isalnum() or c == "_")[:50] if words else "module"
        return f"{safe}_{int(time.time()) % 100000}.py"

    def _generate_code(self, desc: str, filename: str) -> str:
        """Generate a simple template based on the task description."""
        lines = [
            f'"""Auto-generated by OMID AI Developer Agent — {desc}"""\n',
            '__version__ = "1.0.0"\n\n',
            'def main(*args):\n',
            '    """Entry point for this module."""\n',
            '    print("OMID AI module loaded successfully.")\n',
            '\n\nif __name__ == "__main__":\n',
            '    main()\n',
        ]
        return "".join(lines)

    @staticmethod
    def _run_smoke_test(filepath: Path, desc: str) -> bool:
        """Run pytest on the generated module if possible."""
        import importlib.util
        spec = importlib.util.spec_from_file_location(f"omid_temp_{int(time.time()) % 100000}", filepath)
        if spec is None:
            return False
        mod = importlib.util.module_from_spec(spec)
        try:
            spec.loader.exec_module(mod)
            return True
        except Exception:
            return False
